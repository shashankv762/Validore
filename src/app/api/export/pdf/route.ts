import { NextRequest, NextResponse } from 'next/server'
import { renderToBuffer } from '@react-pdf/renderer'
import { createElement } from 'react'
import { createClient } from '@/lib/supabase/server'
import { db } from '@/db'
import { users, validationReports } from '@/db/schema'
import { eq } from 'drizzle-orm'
import { canUserAccess } from '@/lib/tier-gate'

export async function GET(request: NextRequest) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return new NextResponse('Unauthorized', { status: 401 })

  const allowed = await canUserAccess(user.id, 'canExportPdf')
  if (!allowed) return new NextResponse('Upgrade to Premium to export PDF', { status: 403 })

  const reportId = request.nextUrl.searchParams.get('reportId')
  const ideaId = request.nextUrl.searchParams.get('ideaId')
  if (!reportId && !ideaId) return new NextResponse('reportId or ideaId required', { status: 400 })

  const dbUser = await db.query.users.findFirst({ where: eq(users.supabaseId, user.id) })
  if (!dbUser) return new NextResponse('User not found', { status: 404 })

  let report = null
  if (reportId) {
    report = await db.query.validationReports.findFirst({ where: eq(validationReports.id, reportId) })
  } else if (ideaId) {
    report = await db.query.validationReports.findFirst({ 
      where: eq(validationReports.ideaId, ideaId),
      orderBy: (reports, { desc }) => [desc(reports.createdAt)] 
    })
  }

  if (!report || report.userId !== dbUser.id) {
    if (ideaId) {
      // Try crowdfunding analysis
      const { crowdfundingAnalyses, pricingSimulations, leanCanvases } = await import('@/db/schema')
      const { desc: descOrder, and: andOp } = await import('drizzle-orm')

      const cfAnalysis = await db.query.crowdfundingAnalyses.findFirst({
        where: andOp(eq(crowdfundingAnalyses.ideaId, ideaId), eq(crowdfundingAnalyses.userId, dbUser.id)),
        orderBy: [descOrder(crowdfundingAnalyses.createdAt)],
      })

      if (cfAnalysis) {
        const cfData = (cfAnalysis.reportData as Record<string, unknown>) || {}
        const ai = (cfData.ai as Record<string, unknown>) || {}
        const computed = (cfData.computedMetrics as Record<string, unknown>) || {}
        const { Document, Page, Text, View, StyleSheet } = await import('@react-pdf/renderer')
        const styles = StyleSheet.create({
          page: { padding: 40, backgroundColor: '#FAFAF7', fontFamily: 'Helvetica' },
          title: { fontSize: 22, color: '#0A1628', marginBottom: 8 },
          section: { marginBottom: 14 },
          sectionTitle: { fontSize: 13, color: '#0A1628', fontWeight: 'bold', marginBottom: 6, borderBottom: '1px solid #E8E0D0', paddingBottom: 3 },
          text: { fontSize: 10, color: '#1C1C1C', lineHeight: 1.5 },
          badge: { fontSize: 8, color: '#C8A860', marginBottom: 4 },
          footer: { position: 'absolute', bottom: 20, left: 40, right: 40, borderTop: '1px solid #E8E0D0', paddingTop: 6 },
          footerText: { fontSize: 8, color: '#C8A860' },
        })
        const CfPdf = () => createElement(Document, null,
          createElement(Page, { size: 'A4', style: styles.page },
            createElement(View, null,
              createElement(Text, { style: styles.title }, `Crowdfunding Analysis Report`),
              createElement(Text, { style: styles.badge }, `AI_ESTIMATE_UNVERIFIED — Generated by Validore`),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '1. Performance Score'),
              createElement(Text, { style: styles.text }, `Score: ${cfAnalysis.performanceScore || 0}/100 — Band: ${cfAnalysis.classificationBand || 'N/A'}`),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '2. Funding Projections'),
              createElement(Text, { style: styles.text }, `Expected Funding: $${cfAnalysis.expectedFunding || 0}`),
              createElement(Text, { style: styles.text }, `Expected Backers: ${cfAnalysis.expectedBackers || 0}`),
              createElement(Text, { style: styles.text }, `Required Backers: ${(computed as any).requiredBackers || 'N/A'}`),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '3. Recommendation'),
              createElement(Text, { style: styles.text }, cfAnalysis.recommendation || 'See full analysis in dashboard.'),
            ),
            createElement(View, { style: styles.footer },
              createElement(Text, { style: styles.footerText }, 'VALIDORE — Crowdfunding Analysis | SYNTHETIC DATA used for benchmarks'),
            )
          )
        )
        const buffer = await renderToBuffer(createElement(CfPdf))
        return new NextResponse(new Uint8Array(buffer), {
          headers: {
            'Content-Type': 'application/pdf',
            'Content-Disposition': `attachment; filename="crowdfunding-analysis-${cfAnalysis.id.slice(0,8)}.pdf"`,
          },
        })
      }

      // Try pricing simulation
      const prSim = await db.query.pricingSimulations.findFirst({
        where: andOp(eq(pricingSimulations.ideaId, ideaId), eq(pricingSimulations.userId, dbUser.id)),
        orderBy: [descOrder(pricingSimulations.createdAt)],
      })

      if (prSim) {
        const { Document, Page, Text, View, StyleSheet } = await import('@react-pdf/renderer')
        const styles = StyleSheet.create({
          page: { padding: 40, backgroundColor: '#FAFAF7', fontFamily: 'Helvetica' },
          title: { fontSize: 22, color: '#0A1628', marginBottom: 8 },
          section: { marginBottom: 14 },
          sectionTitle: { fontSize: 13, color: '#0A1628', fontWeight: 'bold', marginBottom: 6, borderBottom: '1px solid #E8E0D0', paddingBottom: 3 },
          text: { fontSize: 10, color: '#1C1C1C', lineHeight: 1.5 },
          badge: { fontSize: 8, color: '#C8A860', marginBottom: 4 },
          footer: { position: 'absolute', bottom: 20, left: 40, right: 40, borderTop: '1px solid #E8E0D0', paddingTop: 6 },
          footerText: { fontSize: 8, color: '#C8A860' },
        })
        const PrPdf = () => createElement(Document, null,
          createElement(Page, { size: 'A4', style: styles.page },
            createElement(View, null,
              createElement(Text, { style: styles.title }, `Pricing Strategy Report`),
              createElement(Text, { style: styles.badge }, `PROJECTION — Generated by Validore`),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '1. Pricing Score'),
              createElement(Text, { style: styles.text }, `Score: ${prSim.pricingScore || 0}/100`),
              createElement(Text, { style: styles.text }, `Recommended Price: ${prSim.recommendedPrice || 'N/A'}`),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '2. Scenarios'),
              createElement(Text, { style: styles.text }, JSON.stringify(prSim.scenarios || {}, null, 2).slice(0, 800)),
            ),
            createElement(View, { style: styles.footer },
              createElement(Text, { style: styles.footerText }, 'VALIDORE — Pricing Analysis | PROJECTION badges indicate AI estimates'),
            )
          )
        )
        const buffer = await renderToBuffer(createElement(PrPdf))
        return new NextResponse(new Uint8Array(buffer), {
          headers: {
            'Content-Type': 'application/pdf',
            'Content-Disposition': `attachment; filename="pricing-analysis-${prSim.id.slice(0,8)}.pdf"`,
          },
        })
      }

      // Try lean canvas
      const leanCanvas = await db.query.leanCanvases.findFirst({
        where: andOp(eq(leanCanvases.ideaId, ideaId), eq(leanCanvases.userId, dbUser.id)),
        orderBy: [descOrder(leanCanvases.createdAt)],
      })

      if (leanCanvas) {
        const { Document, Page, Text, View, StyleSheet } = await import('@react-pdf/renderer')
        const styles = StyleSheet.create({
          page: { padding: 40, backgroundColor: '#FAFAF7', fontFamily: 'Helvetica' },
          title: { fontSize: 22, color: '#0A1628', marginBottom: 8 },
          section: { marginBottom: 14 },
          sectionTitle: { fontSize: 13, color: '#0A1628', fontWeight: 'bold', marginBottom: 6, borderBottom: '1px solid #E8E0D0', paddingBottom: 3 },
          text: { fontSize: 10, color: '#1C1C1C', lineHeight: 1.5 },
          badge: { fontSize: 8, color: '#C8A860', marginBottom: 4 },
          footer: { position: 'absolute', bottom: 20, left: 40, right: 40, borderTop: '1px solid #E8E0D0', paddingTop: 6 },
          footerText: { fontSize: 8, color: '#C8A860' },
        })
        const LcPdf = () => createElement(Document, null,
          createElement(Page, { size: 'A4', style: styles.page },
            createElement(View, null,
              createElement(Text, { style: styles.title }, `Lean Canvas Report`),
              createElement(Text, { style: styles.badge }, `AI_ESTIMATE_UNVERIFIED — Generated by Validore`),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '1. Problem'),
              createElement(Text, { style: styles.text }, (leanCanvas.problem as any)?.content || 'Not defined'),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '2. Solution'),
              createElement(Text, { style: styles.text }, (leanCanvas.solution as any)?.content || 'Not defined'),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '3. Unique Value Proposition'),
              createElement(Text, { style: styles.text }, (leanCanvas.uvp as any)?.content || 'Not defined'),
            ),
            createElement(View, { style: styles.section },
              createElement(Text, { style: styles.sectionTitle }, '4. Canvas Confidence Score'),
              createElement(Text, { style: styles.text }, `Score: ${leanCanvas.validationScore || 0}/100`),
            ),
            createElement(View, { style: styles.footer },
              createElement(Text, { style: styles.footerText }, 'VALIDORE — Lean Canvas | ASSUMPTION badges indicate hypothesis-stage data'),
            )
          )
        )
        const buffer = await renderToBuffer(createElement(LcPdf))
        return new NextResponse(new Uint8Array(buffer), {
          headers: {
            'Content-Type': 'application/pdf',
            'Content-Disposition': `attachment; filename="lean-canvas-${leanCanvas.id.slice(0,8)}.pdf"`,
          },
        })
      }

      // Nothing found for any module
      return new NextResponse('No data found for ideaId', { status: 404 })
    }
    return new NextResponse('Not found', { status: 404 })
  }

  const { Document, Page, Text, View, StyleSheet } = await import('@react-pdf/renderer')
  const styles = StyleSheet.create({
    page: { padding: 40, backgroundColor: '#FAFAF7', fontFamily: 'Helvetica' },
    header: { marginBottom: 20 },
    title: { fontSize: 24, color: '#0A1628', marginBottom: 4 },
    subtitle: { fontSize: 12, color: '#C8A860', marginBottom: 16 },
    section: { marginBottom: 16 },
    sectionTitle: { fontSize: 14, color: '#0A1628', fontWeight: 'bold', marginBottom: 8, borderBottom: '1px solid #E8E0D0', paddingBottom: 4 },
    text: { fontSize: 10, color: '#1C1C1C', lineHeight: 1.5 },
    score: { fontSize: 36, color: '#C8A860', fontWeight: 'bold' },
    footer: { position: 'absolute', bottom: 20, left: 40, right: 40, borderTop: '1px solid #E8E0D0', paddingTop: 8, flexDirection: 'row', justifyContent: 'space-between' },
    footerText: { fontSize: 8, color: '#C8A860' },
    watermark: { fontSize: 8, color: '#1C1C1C', opacity: 0.4 },
  })

  const reportData = report.reportData as Record<string, unknown>
  const idea = reportData?.idea as Record<string, string> | undefined

  const PdfDoc = () => createElement(Document, null,
    createElement(Page, { size: 'A4', style: styles.page },
      createElement(View, { style: styles.header },
        createElement(Text, { style: styles.title }, `${idea?.name ?? 'Startup'} — Validation Report`),
        createElement(Text, { style: styles.subtitle }, "Validore AI Validation | Know it's gold before you dig.")
      ),
      createElement(View, { style: styles.section },
        createElement(Text, { style: styles.sectionTitle }, 'Validation Score'),
        createElement(Text, { style: styles.score }, `${report.overallScore ?? 0}/100`),
        createElement(Text, { style: styles.text }, `Decision: ${report.decision ?? 'N/A'}`),
      ),
      createElement(View, { style: styles.section },
        createElement(Text, { style: styles.sectionTitle }, 'Decision Rationale'),
        ...((report.decisionReasons as string[] ?? [])).map((r, i) =>
          createElement(Text, { key: i, style: styles.text }, `• ${r}`)
        ),
      ),
      createElement(View, { style: styles.section },
        createElement(Text, { style: styles.sectionTitle }, 'Key Risks'),
        ...((report.keyRisks as string[] ?? [])).map((r, i) =>
          createElement(Text, { key: i, style: styles.text }, `• ${r}`)
        ),
      ),
      createElement(View, { style: styles.section },
        createElement(Text, { style: styles.sectionTitle }, 'Integrity Note'),
        createElement(Text, { style: styles.text }, (reportData?.integrityNote as string) ?? ''),
      ),
      createElement(View, { style: styles.footer },
        createElement(Text, { style: styles.footerText }, 'validore.app'),
        createElement(Text, { style: styles.watermark }, 'Generated by Validore AI | ASSUMPTIONS and PROJECTIONS are labeled throughout'),
      ),
    )
  )

  const buffer = await renderToBuffer(createElement(PdfDoc))
  return new NextResponse(new Uint8Array(buffer), {
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="validore-validation-${(reportId || ideaId || 'report').slice(0,8)}.pdf"`,
    },
  })
}